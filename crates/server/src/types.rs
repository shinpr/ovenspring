//! The dashboard's TypeScript types, generated from the types the API reads and answers, so the
//! two sides keep one contract. A test fails while `dashboard/src/api/types.gen.ts` differs from
//! what these types generate; `OVENSPRING_WRITE_TYPES=1 cargo test -p ovenspring-server` rewrites it.

use std::any::TypeId;
use std::collections::{BTreeMap, BTreeSet};

use ts_rs::{Config, TS, TypeVisitor};

/// Collects the declaration of every type the roots reach, each once.
struct Declarations {
    config: Config,
    seen: BTreeSet<TypeId>,
    /// Each declaration by its type's name, so the file's order does not follow the order the
    /// compiler happens to visit dependencies in.
    out: BTreeMap<String, String>,
}

impl TypeVisitor for Declarations {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        if T::output_path().is_some() {
            // One file holds every type, so two Rust types of one name would collide in it.
            let name = T::ident(&self.config);
            let docs = T::docs().unwrap_or_default();
            let declared = format!("{docs}export {}", T::decl(&self.config));
            assert!(
                self.out.insert(name.clone(), declared).is_none(),
                "two API types are named {name}; rename one"
            );
        }
        T::visit_dependencies(self);
        T::visit_generics(self);
    }
}

pub(crate) fn generate() -> String {
    let mut d = Declarations {
        config: Config::new().with_large_int("number"),
        seen: BTreeSet::new(),
        out: BTreeMap::new(),
    };
    roots(&mut d);
    format!(
        "// Generated by `crates/server/src/types.rs` from the API's Rust types. Do not edit.\n\n{}\n",
        d.out.into_values().collect::<Vec<_>>().join("\n\n")
    )
}

fn roots(d: &mut Declarations) {
    use ovenspring_core::config::{AgentsConfig, AppConfig, GuardConfig, Limits, ReviewConfig};
    use ovenspring_daemon::history::{EndedSprint, IssueDetail, LaunchDetail, LaunchRow};
    use ovenspring_daemon::overview::Overview;

    d.visit::<Overview>();
    d.visit::<IssueDetail>();
    d.visit::<LaunchRow>();
    d.visit::<LaunchDetail>();
    d.visit::<EndedSprint>();
    d.visit::<crate::settings::Settings>();
    d.visit::<crate::settings::Skills>();
    d.visit::<crate::settings::SettingsSection>();
    d.visit::<crate::settings::GeneralSection>();
    d.visit::<crate::settings::RoleSection>();
    d.visit::<crate::settings::TrackerSection>();
    d.visit::<crate::settings::SlackSection>();
    d.visit::<AgentsConfig>();
    d.visit::<Limits>();
    d.visit::<AppConfig>();
    d.visit::<GuardConfig>();
    d.visit::<ReviewConfig>();
    d.visit::<crate::setup::SetupState>();
    d.visit::<crate::setup::SetupRequest>();
    d.visit::<crate::setup::SetupCheck>();
    d.visit::<crate::setup::SetupFound>();
    d.visit::<crate::setup::RunRequest>();
    d.visit::<crate::api::GoalRequest>();
    d.visit::<crate::api::CancelRequest>();
    d.visit::<crate::api::GoalSaved>();
    d.visit::<crate::api::ApiErrors>();
    d.visit::<crate::version::VersionState>();
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_dashboard_s_api_types_are_generated_from_the_rust_types() {
        let file = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../dashboard/src/api/types.gen.ts");
        let generated = generate();
        if std::env::var_os("OVENSPRING_WRITE_TYPES").is_some() {
            std::fs::write(&file, &generated).unwrap();
        }
        let committed = std::fs::read_to_string(&file).unwrap_or_default();
        assert!(
            committed == generated,
            "{} is out of date: run `OVENSPRING_WRITE_TYPES=1 cargo test -p ovenspring-server`",
            file.display()
        );
    }
}
